-- Задание 1. Самый дорогой товар
SELECT бренд, модель, цена
FROM Товар
ORDER BY цена DESC
LIMIT 1;

-- Задание 2. Самый дешёвый товар
SELECT бренд, модель, цена
FROM Товар
ORDER BY цена ASC
LIMIT 1;

-- Задание 3. Товары категории «Apple»
SELECT бренд, модель, цена
FROM Товар
WHERE бренд = 'Apple';

-- Задание 4. Поиск по названию (буква «о»)
SELECT бренд, модель, цена
FROM Товар
WHERE бренд LIKE '%o%' OR модель LIKE '%o%';

-- Задание 5. Все заказы
SELECT id, дата, клиент, товар_id, количество
FROM Заказ;

-- Задание 6. Заказы конкретного клиента
SELECT *
FROM Заказ
WHERE клиент = 'Иванов Иван Иванович';

-- Задание 7. JOIN — заказы с названиями товаров
SELECT Заказ.дата,
       Заказ.клиент,
       Товар.бренд || ' ' || Товар.модель AS товар,
       Заказ.количество
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 8. Общая сумма всех заказов
SELECT SUM(Товар.цена * Заказ.количество) AS итого
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 9. Количество заказов по клиентам
SELECT клиент, COUNT(*) AS кол_заказов
FROM Заказ
GROUP BY клиент;

-- Задание 10. Мой запрос
SELECT бренд, AVG(цена) AS средняя_цена
FROM Товар
GROUP BY бренд
ORDER BY средняя_цена DESC;